  "join" "$PROD_SERVER_URL" "false" "" ""

write_vm_decl "$GENERATED_DIR/vars/vms/${PROXMOX_HOST2_NAME}-k3s-test.yml" \
  "${PROXMOX_HOST2_NAME}-k3s-test" "$K3S_VM_HOST2_TEST_VMID" "$K3S_VM_HOST2_TEST_CORES" \
  "$K3S_VM_HOST2_TEST_MEMORY_MB" "$K3S_VM_HOST2_TEST_DISK_GB" "$K3S_VM_HOST2_TEST_IP" \
  "join" "$TEST_SERVER_URL" "false" "$K3S_TEST_CLUSTER_CIDR" "$K3S_TEST_SERVICE_CIDR"

write_vm_decl "$GENERATED_DIR/vars/vms/${PROXMOX_HOST3_NAME}-k3s.yml" \
  "${PROXMOX_HOST3_NAME}-k3s" "$K3S_VM_HOST3_VMID" "$K3S_VM_HOST3_CORES" \
  "$K3S_VM_HOST3_MEMORY_MB" "$K3S_VM_HOST3_DISK_GB" "$K3S_VM_HOST3_IP" \
  "join" "$PROD_SERVER_URL" "${K3S_VM_HOST3_CONTROL_PLANE_ONLY:-false}" "" ""

write_vm_decl "$GENERATED_DIR/vars/vms/${PROXMOX_HOST3_NAME}-k3s-test.yml" \
  "${PROXMOX_HOST3_NAME}-k3s-test" "$K3S_VM_HOST3_TEST_VMID" "$K3S_VM_HOST3_TEST_CORES" \
  "$K3S_VM_HOST3_TEST_MEMORY_MB" "$K3S_VM_HOST3_TEST_DISK_GB" "$K3S_VM_HOST3_TEST_IP" \
  "join" "$TEST_SERVER_URL" "false" "$K3S_TEST_CLUSTER_CIDR" "$K3S_TEST_SERVICE_CIDR"

# ── one guest declaration per configured core service, all on host1 ───────
# 🔵 Concentrated on host1 by default, not ranked by hardware strength — see config.sh-template's
# own comment. VMIDs/sizing below match the values proven on the reference lab
# (platform/MIGRATION-services.md); override by editing this script if your hardware differs.
mkdir -p "$GENERATED_DIR/vars/core-services"
mkdir -p "$GENERATED_DIR/vars/lab-extras"

# Shared by write_core_service (below) and the LAB_EXTRAS loop further down — same guest:/service:
# declaration shape either way, just a different output directory and a different source list
# (CORE_SERVICES vs LAB_EXTRAS). See config.sh-template's "Lab extras" section for why these are
# two separate lists rather than one, even though the declaration shape itself doesn't care.
write_guest_decl() {
  local outdir="$1" name="$2" vmid="$3" cores="$4" mem="$5" swap="$6" startup="$7" \
        features="$8" rootfs_gb="$9" mount_mp="${10}" mount_gb="${11}" recordsize="${12}" role="${13}" \
        ip="${14}" extra_mounts="${15:-}"
  local file="$GENERATED_DIR/vars/${outdir}/${name}.yml"
  cat > "$file" <<EOF
# GENERATED from config.sh by generate-ansible-config.sh — do not hand-edit.
guest:
  name: ${name}
  vmid: ${vmid}
  kind: lxc
  ostype: debian
  template: "debian-13-standard_13.6-1_amd64.tar.zst"
  cores: ${cores}
  memory: ${mem}
  swap: ${swap}
  unprivileged: true
EOF
  [[ -n "$features" ]] && echo "  features: \"${features}\"" >> "$file"
  cat >> "$file" <<EOF
  onboot: true
  startup: "${startup}"
  rootfs:
    storage: ${PROXMOX_STORAGE}
    size_gb: ${rootfs_gb}
EOF
  if [[ -n "$mount_mp" ]]; then
    cat >> "$file" <<EOF
  mounts:
    - id: mp0
      storage: ${PROXMOX_STORAGE}
      size_gb: ${mount_gb}
      mountpoint: ${mount_mp}
EOF
    [[ -n "$recordsize" ]] && echo "      zfs_recordsize: ${recordsize}" >> "$file"
  fi
  # 🔵 ADDITIONAL mounts beyond mp0 — "path:size_gb" pairs, comma-separated. Added for nas
  # (urb-agents#1970/#1978), the first guest here with more than one real Proxmox-managed storage
  # volume (deliberately NOT a host bind mount — `pvesr`: "unable to replicate mountpoint type
  # 'bind'", so a bind mount's data would not follow this guest on HA failover; see
  # roles/nas/tasks/main.yml's own header). Every existing caller passes this empty, so mp0's own
  # params above are untouched — this only adds mp1, mp2, ... when a guest declares more than one.
  if [[ -n "$extra_mounts" ]]; then
    local _mp_idx=1 _pair _mpath _msize
    IFS=',' read -ra _extra_mount_pairs <<< "$extra_mounts"
    for _pair in "${_extra_mount_pairs[@]}"; do
      _mpath="${_pair%%:*}"
      _msize="${_pair#*:}"
      if [[ "$_mp_idx" -eq 1 && -z "$mount_mp" ]]; then
        echo "  mounts:" >> "$file"
      fi
      cat >> "$file" <<EOF
    - id: mp${_mp_idx}
      storage: ${PROXMOX_STORAGE}
      size_gb: ${_msize}
      mountpoint: ${_mpath}
EOF
      _mp_idx=$((_mp_idx + 1))
    done
  fi
  cat >> "$file" <<EOF
  nets:
    - id: net0
      bridge: vmbr0
      ip: "${ip}/${NETWORK_PREFIX_LENGTH}"
      gw: ${NETWORK_GATEWAY}

service:
  kind: lxc
  role: ${role}
  playbook: playbooks/service-${name}.yml
  health: vars/${name}-health.yml
EOF
  ZONE_ENTRIES+=("${name}:${ip}")
}

write_core_service() {
  write_guest_decl "core-services" "$@"
}

# write_vm_extra_decl <name> <vmid> <cores> <mem_mb> <disk_gb> <ip> <role>
#
# 🔵 THE VM COUNTERPART TO write_guest_decl, for a lab-extra that needs a QEMU VM instead of an
# LXC container — forgejo-runner is the first (urb-agents#1982: it runs Docker, and nesting
# Docker-in-LXC is its own can of worms this platform has never needed to open; a VM sidesteps it
# entirely, same choice the reference lab made for its own epinio-runner). Writes the SAME `vm:`
# shape write_vm_decl already writes for the six k3s VMs (vm-ensure.yml reads this block and has
# never been k3s-aware — see that function's own header), but with NO `k3s:` block, since nothing
# here ever installs k3s on it. `service.kind: vm` is what 09-lab-extras-apply.sh branches on to
# call vm-ensure.yml instead of guest-ensure.yml, and to skip the replicate+HA-register steps that
# make sense for a stateful LXC guest but not for disposable CI-runner compute.
write_vm_extra_decl() {
  local name="$1" vmid="$2" cores="$3" mem="$4" disk="$5" ip="$6" role="$7"
  local file="$GENERATED_DIR/vars/lab-extras/${name}.yml"
  cat > "$file" <<EOF
# GENERATED from config.sh by generate-ansible-config.sh — do not hand-edit.
vm:
  name: ${name}
  vmid: ${vmid}
  cores: ${cores}
  memory: ${mem}
  disk_gb: ${disk}
  storage: ${PROXMOX_STORAGE}
  bridge: vmbr0
  cloud_image: ${VM_CLOUD_IMAGE}
  cloud_image_url: "${VM_CLOUD_IMAGE_URL}"
  ip: "${ip}/${NETWORK_PREFIX_LENGTH}"
  gateway: "${NETWORK_GATEWAY}"
  nameserver: "${NETWORK_DNS}"
  searchdomain: ${NETWORK_SEARCH_DOMAIN}
  ciuser: ${VM_CIUSER}

service:
  kind: vm
  role: ${role}
  playbook: playbooks/service-${name}.yml
EOF
  ZONE_ENTRIES+=("${name}:${ip}")
}

# 🔴 OVERRIDABLE, NOT RE-HARDCODED PER LAB. Config.sh-template documents when to set one of
# these: a real cluster can already have an unrelated guest at the default VMID, or the real
# service guest can have been built independently (before this convention existed) at a
# different one. Live-confirmed, urb-agents#1940: a hardcoded 410 for forgejo collided with an
# unrelated real guest (dns-resolver) on a lab whose actual Forgejo was at 411 — guest-ensure.yml
# and the scoped-run IP-lookup fallback both trusted the VMID alone and silently resolved the
# wrong guest. Defaults below are unchanged from before; nothing changes for a lab that never sets
# an override.
CORE_SERVICE_PG_VMID="${CORE_SERVICE_PG_VMID:-405}"
CORE_SERVICE_PG_TEST_VMID="${CORE_SERVICE_PG_TEST_VMID:-406}"
CORE_SERVICE_GARAGE_VMID="${CORE_SERVICE_GARAGE_VMID:-407}"
CORE_SERVICE_BAO_VMID="${CORE_SERVICE_BAO_VMID:-408}"
CORE_SERVICE_REGISTRY_VMID="${CORE_SERVICE_REGISTRY_VMID:-409}"
CORE_SERVICE_FORGEJO_VMID="${CORE_SERVICE_FORGEJO_VMID:-410}"

for svc in $CORE_SERVICES; do
  case "$svc" in
    pg)       write_core_service pg       "$CORE_SERVICE_PG_VMID"       4 8192 1024 "order=4" ""                  8  /var/lib/postgresql 200 16K postgres "$CORE_SERVICE_PG_IP" ;;
    bao)      write_core_service bao      "$CORE_SERVICE_BAO_VMID"      2 1024 512  "order=2" ""                  8  /var/lib/openbao    10  ""  bao "$CORE_SERVICE_BAO_IP" ;;
    garage)   write_core_service garage   "$CORE_SERVICE_GARAGE_VMID"   2 2048 512  "order=3" "nesting=1,keyctl=1" 8  /var/lib/garage     100 ""  garage "$CORE_SERVICE_GARAGE_IP" ;;
    registry) write_core_service registry "$CORE_SERVICE_REGISTRY_VMID" 2 1024 512  "order=1" "nesting=1,keyctl=1" 8  /var/lib/registry   60  ""  registry "$CORE_SERVICE_REGISTRY_IP" ;;
    # 🔵 A SEPARATE guest, not a database inside "pg" — the test cluster must never be able to
    # read or corrupt production data. Smaller than pg on purpose: test data, test stakes.
    pg-test)  write_core_service pg-test  "$CORE_SERVICE_PG_TEST_VMID"  2 2048 512  "order=5" ""                  8  /var/lib/postgresql 20  16K postgres "$CORE_SERVICE_PG_TEST_IP" ;;
    # Self-hosted git host + its own built-in OCI registry — see roles/forgejo and
    # PLAN-system-forgejo-core-service.md. order=6: every other order value above is already
    # taken; Forgejo has no startup dependency on any of them.
    forgejo)  write_core_service forgejo  "$CORE_SERVICE_FORGEJO_VMID"  2 2048 512  "order=6" "nesting=1,keyctl=1" 8  /var/lib/forgejo    50  ""  forgejo "$CORE_SERVICE_FORGEJO_IP" ;;
    *) echo "⚠️  Unknown core service '$svc' in CORE_SERVICES — skipped" >&2 ;;
  esac
done

# ── one guest declaration per configured lab extra — opt-in, NOT CORE_SERVICES ─────────────────
# See config.sh-template's "Lab extras" section (urb-agents#1970/#1971/#1972) for why this is a
# separate list rather than a 7th CORE_SERVICES case arm — keeping it visibly separate is the
# whole point, not an implementation detail.
# 🔴 KEEP THIS LIST IN STEP WITH scripts/08-lab-extra-add.sh's OWN `case "$NAME" in` ARM — same
# "two places must agree" shape 07-core-service-add.sh's header already names for CORE_SERVICES.
LAB_EXTRA_DNS_RESOLVER_VMID="${LAB_EXTRA_DNS_RESOLVER_VMID:-400}"
LAB_EXTRA_NAS_VMID="${LAB_EXTRA_NAS_VMID:-404}"
# 🔵 "path:size_gb" pairs, comma-separated — one Proxmox-managed storage volume per declared
# share (deliberately NOT a host bind mount, same reasoning as roles/nas/tasks/main.yml's own
# header: a bind mount cannot be replicated by Proxmox, so its data would not follow this guest on
# HA failover). The FIRST pair becomes mp0, any further ones mp1/mp2/... via write_guest_decl's
# own extra_mounts param. Each path here must match one `nas_shares[].path` in the lab owner's own
# site-data file (see README.md's "Lab extras" section) — this script only provisions the storage,
# it has no view into what Samba will call it or who may read it.
# 🔴 ONE SHARE BY DEFAULT, not the reference lab's two. The reference's second share is
# deliberately guest-writable with NO AUTHENTICATION at all — a real, informed, site-specific
# trust decision (Terje, 2026-10-01: "the LAN is trusted"), not something a generic UIS default
# should hand a fresh lab owner. Add a second path:size_gb pair here (and a matching nas_shares
# entry in the site-data file) if you want one.
LAB_EXTRA_NAS_SHARE_MOUNTS="${LAB_EXTRA_NAS_SHARE_MOUNTS:-/srv/shared:50}"
# 🔵 VMID 411 — right after forgejo's own 410, no collision with anything else this template
# defaults (400 dns-resolver, 404 nas, 405-410 pg/pg-test/garage/bao/registry/forgejo, 490/491/
# 290/291/190/191 the six k3s VMs). Sized 4 cores/8192MB/40GB — not a guess, the reference lab's
# own real epinio-runner guest at this exact workload (Docker image builds), proven live.
LAB_EXTRA_FORGEJO_RUNNER_VMID="${LAB_EXTRA_FORGEJO_RUNNER_VMID:-411}"

for extra in $LAB_EXTRAS; do
  case "$extra" in
    # order=0 — before everything, INCLUDING registry's order=1. Tiny on purpose: a single
    # dnsmasq process and a generated zone file, no database, nothing here that outlives a
    # rebuild — same reasoning as the reference lab's own declaration.
    dns-resolver) write_guest_decl lab-extras dns-resolver "$LAB_EXTRA_DNS_RESOLVER_VMID" 1 512 256 "order=0" "" 4 "" "" "" dns-resolver "$LAB_EXTRA_DNS_RESOLVER_IP" ;;
    # order=3 — matches the reference lab's own declaration; no startup dependency on anything
    # else here (unlike dns-resolver's order=0, nothing else needs nas up before it can start).
    nas)
      _nas_first_mount="${LAB_EXTRA_NAS_SHARE_MOUNTS%%,*}"
      _nas_first_path="${_nas_first_mount%%:*}"
      _nas_first_size="${_nas_first_mount#*:}"
      _nas_rest_mounts=""
      [[ "$LAB_EXTRA_NAS_SHARE_MOUNTS" == *,* ]] && _nas_rest_mounts="${LAB_EXTRA_NAS_SHARE_MOUNTS#*,}"
      write_guest_decl lab-extras nas "$LAB_EXTRA_NAS_VMID" 2 1024 512 "order=3" "" 8 \
        "$_nas_first_path" "$_nas_first_size" "" nas "$LAB_EXTRA_NAS_IP" "$_nas_rest_mounts"
      ;;
    # 🔴 DEPENDS ON forgejo BEING A SELECTED CORE_SERVICES ENTRY — unlike dns-resolver/nas, which
    # both stand alone, a CI runner with nothing to register against is useless. Refuse loudly at
    # generation time rather than silently building a VM that can never finish its own
    # registration task (urb-agents#1982's own open question, confirmed by ops/Terje: build it).
    forgejo-runner)
      _fr_has_forgejo=0
      for _svc in $CORE_SERVICES; do [[ "$_svc" == "forgejo" ]] && _fr_has_forgejo=1 && break; done
      if [[ "$_fr_has_forgejo" -eq 0 ]]; then
        echo "✗ forgejo-runner is in LAB_EXTRAS but 'forgejo' is not in CORE_SERVICES — run" >&2
        echo "  'uis platform core-service add proxmox forgejo' first; a runner with no Forgejo" >&2
        echo "  instance to register against is useless." >&2
        exit 1
      fi
      write_vm_extra_decl forgejo-runner "$LAB_EXTRA_FORGEJO_RUNNER_VMID" 4 8192 40 \
        "$LAB_EXTRA_FORGEJO_RUNNER_IP" forgejo-runner
      ;;
    *) echo "⚠️  Unknown lab extra '$extra' in LAB_EXTRAS — skipped" >&2 ;;
  esac
done

# ── per-service secrets/site-data, generated once and reused on every re-run ───────────────────
# 🔴 SECRETS LIVE ONLY HERE, gitignored (ansible/generated/), never in a committed declaration —
# same rule config.sh's own PROXMOX_SSH_KEY already follows. garage's role refuses to run without
# these (no sane default — a generated-and-forgotten credential is nobody's idea of a secret
# store).
# 🔴 WITHOUT THIS, "confirm/repair" SILENTLY REPLACES A REAL FIREWALL WITH AN EMPTY ONE.
# <role>_firewall_allow_hosts/_ranges default to [] IN THE ROLE ITSELF, by design — "declare the
# real allow-list per site, not in a reusable role". Nothing upstream of the role was ever wired
# to supply one, so every service-<name>.yml run rendered the role's own empty default and
# applied it — live-confirmed, urb-agents#1944: this silently tore down garage's real, live
# allow-list (caught and reverted by hand before it mattered) and would have done the same to
# forgejo (its own CI pipeline) or bao (admin access) the moment their turn came. Emits only
# `_firewall_allow_ranges` (raw "start-end" address ranges) — not `_firewall_allow_hosts`
# (inventory hostnames resolved via hostvars), since a lab's real admin hosts (an ops box, a CI
# runner) are not necessarily guests this platform's own generated inventory knows about at all;
# a single host is just its own address on both ends of a range.
_firewall_ranges_yaml() {
  local raw="$1" r
  [[ -z "$raw" ]] && return 0
  IFS=',' read -ra _ranges <<< "$raw"
  for r in "${_ranges[@]}"; do
    r="$(echo "$r" | xargs)"
    [[ -n "$r" ]] && echo "  - \"${r}\""
  done
}

EXTRA_VARS_FILE="$GENERATED_DIR/vars/core-services/_extra-vars.yml"
{
  echo "# GENERATED by generate-ansible-config.sh — secrets + site data, gitignored. Do not commit."
  pg_networks_written=0
  pg_firewall_written=0
  for svc in $CORE_SERVICES; do
    case "$svc" in
      garage)
        if [[ ! -f "$EXTRA_VARS_FILE" ]] || ! grep -q "^garage_access_key:" "$EXTRA_VARS_FILE" 2>/dev/null; then
          echo "garage_access_key: \"GK$(openssl rand -hex 12)\""
          echo "garage_secret_key: \"$(openssl rand -hex 32)\""
          echo "garage_rpc_secret: \"$(openssl rand -hex 32)\""
        fi
        if [[ -n "${CORE_SERVICE_GARAGE_FIREWALL_ALLOW_RANGES:-}" ]]; then
          echo "garage_firewall_allow_ranges:"
          _firewall_ranges_yaml "$CORE_SERVICE_GARAGE_FIREWALL_ALLOW_RANGES"
        fi
        ;;
      bao)
        if [[ -n "${CORE_SERVICE_BAO_FIREWALL_ALLOW_RANGES:-}" ]]; then
          echo "bao_firewall_allow_ranges:"
          _firewall_ranges_yaml "$CORE_SERVICE_BAO_FIREWALL_ALLOW_RANGES"
        fi
        ;;
      forgejo)
        if [[ -n "${CORE_SERVICE_FORGEJO_FIREWALL_ALLOW_RANGES:-}" ]]; then
          echo "forgejo_firewall_allow_ranges:"
          _firewall_ranges_yaml "$CORE_SERVICE_FORGEJO_FIREWALL_ALLOW_RANGES"
        fi
        # 🔴 NO AUTO-GENERATE HERE, unlike garage's bootstrap credential — these are Forgejo's
        # OWN app secrets, and the real reference role never auto-generates them either; an
        # operator runs `forgejo generate secret <TYPE>` once and supplies the result, same as
        # an adopted lab's real, already-running instance must (urb-agents#1945). Emitted only
        # when set — left unset, the role's own assert refuses with the exact commands to run,
        # same message either way, rather than this layer silently inventing a wrong-shaped one.
        [[ -n "${CORE_SERVICE_FORGEJO_SECRET_KEY:-}" ]] && echo "forgejo_secret_key: \"${CORE_SERVICE_FORGEJO_SECRET_KEY}\""
        [[ -n "${CORE_SERVICE_FORGEJO_INTERNAL_TOKEN:-}" ]] && echo "forgejo_internal_token: \"${CORE_SERVICE_FORGEJO_INTERNAL_TOKEN}\""
        [[ -n "${CORE_SERVICE_FORGEJO_JWT_SECRET:-}" ]] && echo "forgejo_jwt_secret: \"${CORE_SERVICE_FORGEJO_JWT_SECRET}\""
        ;;
      pg|pg-test)
        # 🔴 WITHOUT THIS, uis deploy postgresql's external-service proxy cannot reach this
        # guest at all — found running it for real (2026-10-05): the proxy's connection is
        # SNAT'd to the k3s NODE's own address, which pg_hba.conf never heard of otherwise.
        # Appended to the role's own loopback-only default, not replacing it — local psql
        # from inside the guest must keep working too. Emitted once even if both pg and
        # pg-test are selected (identical fix, same shared CORE_SERVICES_LAN_CIDR).
        if [[ "$pg_networks_written" -eq 0 ]]; then
          cat <<EOF
pg_allowed_networks:
  - { cidr: "127.0.0.1/32", why: "loopback" }
  - { cidr: "::1/128", why: "loopback" }
  - { cidr: "${CORE_SERVICES_LAN_CIDR}", why: "k3s nodes and core-services guests — the external-service proxy's connection is SNAT'd to the k3s node's own address" }
EOF
          pg_networks_written=1
        fi
        # 🔵 pg and pg-test SHARE this value — both run through this same shared extra-vars
        # file, so there is currently no way for them to have DIFFERENT real-world allow-lists,
        # only the SAME one or neither. Emitted once even if both are selected.
        if [[ "$pg_firewall_written" -eq 0 ]] && [[ -n "${CORE_SERVICE_PG_FIREWALL_ALLOW_RANGES:-}" ]]; then
          echo "pg_firewall_allow_ranges:"
          _firewall_ranges_yaml "$CORE_SERVICE_PG_FIREWALL_ALLOW_RANGES"
          pg_firewall_written=1
        fi
        ;;
    esac
  done
} > "${EXTRA_VARS_FILE}.new"
# Preserve a previously-generated garage secret across re-runs (regenerating it would orphan the
# already-bootstrapped credential on a live guest) — only write secrets that don't already exist.
# 🔴 NAMED KEYS ONLY, not a bare `^garage_` prefix — garage_firewall_allow_ranges (and its
# indented list items, which never start with `garage_` and so would be left orphaned by a
# broader grep -v) is DETERMINISTIC from config.sh and regenerated fresh every run; it must never
# be swept into this random-secret-preservation dance, which was never meant to touch it.
if [[ -f "$EXTRA_VARS_FILE" ]]; then
  grep -E "^garage_(access_key|secret_key|rpc_secret):" "$EXTRA_VARS_FILE" > /tmp/.garage-secrets.$$ 2>/dev/null || true
  if [[ -s /tmp/.garage-secrets.$$ ]]; then
    grep -vE "^garage_(access_key|secret_key|rpc_secret):" "${EXTRA_VARS_FILE}.new" > /tmp/.extra-rest.$$
    cat /tmp/.extra-rest.$$ /tmp/.garage-secrets.$$ > "${EXTRA_VARS_FILE}.new"
    rm -f /tmp/.extra-rest.$$
  fi
  rm -f /tmp/.garage-secrets.$$
fi
mv "${EXTRA_VARS_FILE}.new" "$EXTRA_VARS_FILE"

# ── lab-extras' own extra-vars — ONE shared file, each selected extra APPENDS its own section ──
# 🔴 APPEND, NOT EACH-OVERWRITES — this file holds every selected lab extra's vars together (same
# shape as CORE_SERVICES' own shared _extra-vars.yml), not one-file-per-extra. An earlier version
# of this had dns-resolver and nas each truncate the same file with `>`, which would silently drop
# whichever one generated first the moment both were ever selected together.
# 🔵 ZONE_ENTRIES is complete by this point regardless of ordering: every write_vm_decl/
# write_guest_decl call above (6 k3s VMs, every configured CORE_SERVICES guest, every lab-extra's
# own self-entry) already appended to it as a side effect.
LAB_EXTRAS_VARS_FILE="$GENERATED_DIR/vars/lab-extras/_extra-vars.yml"
_lab_extras_has() {
    local want="$1" _e
    for _e in $LAB_EXTRAS; do [[ "$_e" == "$want" ]] && return 0; done
    return 1
}
echo "# GENERATED by generate-ansible-config.sh — do not hand-edit." > "$LAB_EXTRAS_VARS_FILE"

if _lab_extras_has dns-resolver; then
  {
    echo "dns_resolver_zone_entries:"
    for _entry in "${ZONE_ENTRIES[@]}"; do
      _ename="${_entry%%:*}"
      _eip="${_entry#*:}"
      echo "  - { name: \"${_ename}\", ip: \"${_eip}\" }"
    done
    echo "dns_resolver_upstream: \"${NETWORK_DNS}\""
    echo "dns_resolver_domain: \"${NETWORK_SEARCH_DOMAIN}\""
    # 🔴 THE ONE DELIBERATE EXCEPTION TO "NEVER DEFAULT A REAL ALLOW-LIST" — see
    # roles/dns-resolver/defaults/main.yml and config.sh-template's own comment for why. `${VAR+x}`
    # distinguishes "never set" (use the whole-LAN default) from "set, even to empty" (the lab
