#!/bin/bash
# File: platforms/proxmox/scripts/forgejo-runner-pod-deploy.sh
#
# Description:
#   Deploy the Forgejo Actions CI runner as a k3s pod on this platform's own production
#   cluster. NOT a Proxmox guest — not an LXC, not a VM, nothing for 08-lab-extra-add.sh/
#   09-lab-extras-apply.sh to build — so this is a thin wrapper around the SAME UIS-wide
#   `uis deploy forgejo-runner` service (/mnt/urbalurbadisk/ansible/playbooks/
#   640-setup-forgejo-runner.yml, manifests/640-forgejo-runner.yaml.j2) that already runs
#   on Rancher Desktop, not a second, duplicated mechanism (urb-agents#1982: "k3s is k3s...
#   one implementation, both platform targets," the same reasoning bao+ESO already use).
#
#   The ONE real difference that playbook needs told explicitly: forgejo here is an
#   EXTERNAL CORE_SERVICES LXC guest (a real LAN address), not an in-cluster Deployment —
#   so this script resolves that address from config.sh and passes it as
#   `-e forgejo_external_url=...`, the same documented workaround
#   service-forgejo-runner.sh's own header comment already uses for the pre-existing
#   `uis deploy <service> -- -e key=value` CLI gap (urb-agents#1928) — not a new invention.
#
#   This is the pod-based successor to platforms/proxmox/ansible/roles/forgejo-runner/'s own
#   VM-based lab extra (PR #611→#616, built via `uis platform lab-extra add proxmox
#   forgejo-runner`). That VM-kind lab extra is kept standing per ops's own explicit
#   instruction until THIS is live-verified — do not remove it here.
#
# Prerequisites:
#   - `forgejo` in CORE_SERVICES and already built (same dependency the VM-kind lab extra
#     enforces)
#   - .uis.secrets/platforms/proxmox/lab-extras/forgejo-runner-site-data.yml filled in with
#     a real registration token — same site-data-file convention PR #616 introduced,
#     reused here as-is: the token is the same genuine site data regardless of which
#     mechanism consumes it, not worth a second convention for one field. See
#     platforms/proxmox/lab-extras-site-data/forgejo-runner-site-data.yml-template.
#   - scripts/04-k3s-post-apply.sh has run at least once (so the "proxmox" kubectl context
#     exists in the merged kubeconfig at all)
#
# Usage:
#   ./scripts/forgejo-runner-pod-deploy.sh

set -euo pipefail

RED='\033[0;31m'; GREEN='\033[0;32m'; YELLOW='\033[1;33m'; BLUE='\033[0;34m'; NC='\033[0m'
print_status()  { echo -e "${BLUE}[INFO]${NC} $1"; }
print_success() { echo -e "${GREEN}[SUCCESS]${NC} $1"; }
print_warning() { echo -e "${YELLOW}[WARNING]${NC} $1"; }
print_error()   { echo -e "${RED}[ERROR]${NC} $1"; }
print_section() { echo; echo -e "${GREEN}========================================${NC}"; echo -e "${GREEN}$1${NC}"; echo -e "${GREEN}========================================${NC}"; echo; }

if [[ ! -f /.dockerenv ]] || [[ ! -d /mnt/urbalurbadisk ]]; then
    print_error "This script must run inside the provision-host container"
    exit 1
fi

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PLATFORM_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"
# config.sh is per-install REAL STATE -- see every other script in this directory's own
# comment on this; same urb-agents#1935 reasoning, not repeated here.
REPO_ROOT="${UIS_REPO_ROOT:-$(cd "$PLATFORM_DIR/../.." && pwd)}"
CONFIG_FILE="$REPO_ROOT/.uis.secrets/platforms/proxmox/config.sh"

print_section "PROXMOX — FORGEJO RUNNER (pod-based, k3s)"

if [[ ! -f "$CONFIG_FILE" ]]; then
    print_error "No config.sh found at $CONFIG_FILE — run 'uis platform init proxmox' first."
    exit 1
fi
# shellcheck source=/dev/null
source "$CONFIG_FILE"
CORE_SERVICES="${CORE_SERVICES:-}"

# 🔴 SAME forgejo DEPENDENCY the VM-kind lab extra enforces (urb-agents#1982) — a runner with
# no Forgejo instance to register against is useless either way it's built.
_has_forgejo=0
for _svc in $CORE_SERVICES; do [[ "$_svc" == "forgejo" ]] && _has_forgejo=1 && break; done
if [[ "$_has_forgejo" -eq 0 ]]; then
    print_error "forgejo-runner needs 'forgejo' in CORE_SERVICES first — it has nothing to register against otherwise."
    echo "  Run 'uis platform core-service add proxmox forgejo' first." >&2
    exit 1
fi
if [[ -z "${CORE_SERVICE_FORGEJO_IP:-}" ]]; then
    print_error "CORE_SERVICE_FORGEJO_IP is not set in config.sh."
    exit 1
fi

# 🔵 SAME SITE-DATA FILE PR #616 INTRODUCED — see that convention's own reasoning
# (lab-extras-site-data/forgejo-runner-site-data.yml-template): a registration token is
# genuine site data, never defaulted, never generated by this script.
SITE_DATA_FILE="$REPO_ROOT/.uis.secrets/platforms/proxmox/lab-extras/forgejo-runner-site-data.yml"
if [[ ! -f "$SITE_DATA_FILE" ]]; then
    print_error "No registration token found at $SITE_DATA_FILE"
    echo "  Copy platforms/proxmox/lab-extras-site-data/forgejo-runner-site-data.yml-template" >&2
    echo "  there and fill in a real token first:" >&2
    echo "    ssh <forgejo guest IP> docker exec --user git forgejo forgejo actions generate-runner-token" >&2
    exit 1
fi
FORGEJO_RUNNER_TOKEN="$(grep -m1 '^forgejo_runner_token:' "$SITE_DATA_FILE" | sed -E 's/^forgejo_runner_token:[[:space:]]*"?//; s/"?[[:space:]]*$//')"
if [[ -z "$FORGEJO_RUNNER_TOKEN" ]]; then
    print_error "forgejo_runner_token in $SITE_DATA_FILE is empty — fill in a real one first."
    exit 1
fi

FORGEJO_EXTERNAL_URL="http://${CORE_SERVICE_FORGEJO_IP}:3000/"

print_status "Switching the active cluster target to proxmox..."
# shellcheck source=/dev/null
source /mnt/urbalurbadisk/provision-host/uis/lib/platform-switching.sh
# 🔴 SAME pf_lockstep_flip point-postgresql-at.sh already uses, same reason: the setup
# playbook's own kubernetes.core.k8s_info/k8s tasks trust the merged kubeconfig's
# CURRENT-CONTEXT, not target_host (that var is for messages/validation only) — nothing in
# this flow switches it for us otherwise.
pf_lockstep_flip proxmox

print_status "Deploying the Forgejo Actions runner against forgejo at ${FORGEJO_EXTERNAL_URL}..."
cd /mnt/urbalurbadisk
ansible-playbook ansible/playbooks/640-setup-forgejo-runner.yml \
    -e target_host=proxmox \
    -e "forgejo_external_url=${FORGEJO_EXTERNAL_URL}" \
    -e "forgejo_runner_token=${FORGEJO_RUNNER_TOKEN}"

print_success "Forgejo Runner deployed against proxmox's own k3s cluster."
